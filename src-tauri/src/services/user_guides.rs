/// 首次启动时注入使用指南
pub fn inject_if_needed() {
    let stored_version = crate::database::get(
        "SELECT content FROM memories WHERE content LIKE '[GUIDES_VERSION]%' LIMIT 1",
        &[],
    ).ok().flatten()
     .and_then(|r| r["content"].as_str().map(|s| s.to_string()));

    if stored_version.as_deref() == Some(&format!("[GUIDES_VERSION] {}", GUIDES_VERSION)) {
        return;
    }

    log::info!("[UserGuides] injecting guides (version: {})...", GUIDES_VERSION);

    crate::database::run("DELETE FROM memories WHERE content LIKE '[GUIDE] %'", &[]).ok();
    crate::database::run("DELETE FROM memories WHERE content LIKE '[GUIDES_VERSION] %'", &[]).ok();

    let mut count = 0u32;
    for (title, _keywords, content) in GUIDES {
        let id = uuid::Uuid::new_v4().to_string();
        let guide_content = format!("[GUIDE] {}: {}", title, content);
        if crate::database::run(
            "INSERT INTO memories(id, content, updated_at) VALUES(?1, ?2, datetime('now','localtime'))",
            &[serde_json::json!(&id), serde_json::json!(&guide_content)],
        ).is_ok() {
            count += 1;
        }
    }

    let ver_id = uuid::Uuid::new_v4().to_string();
    crate::database::run(
        "INSERT INTO memories(id, content, updated_at) VALUES(?1, ?2, datetime('now','localtime'))",
        &[serde_json::json!(&ver_id), serde_json::json!(format!("[GUIDES_VERSION] {}", GUIDES_VERSION))],
    ).ok();

    log::info!("[UserGuides] injected {} guides", count);
}
